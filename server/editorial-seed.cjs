function seedEditorial(db, store) {
  const marker = "editorial-collection-20261019";
  if (db.prepare("SELECT key FROM garden_meta WHERE key=?").get(marker)) return;
  db.transaction(() => {
    for (const [kind, items] of [
      ["posts", posts],
      ["books", books],
    ]) {
      for (const item of items)
        if (!store.get(kind, item.slug, true))
          store.save(kind, item.id, item, "publish");
    }
    db.prepare("INSERT INTO garden_meta(key,value) VALUES(?,?)").run(
      marker,
      "1",
    );
  })();
}
